#!/usr/bin/env python
"""Generate _toc.yml + _config.yml for Jupyter Book from the notebooks that exist, then build.

Usage:  /home/dominik/miniconda3/envs/mri-book/bin/python _authoring/make_book.py [--no-build]
Output: ROOT/_build/html/index.html
Notebooks are rendered from their stored outputs (no re-execution).
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

PARTS = [
    ("Pass 1 — The big picture", "pass1_big_picture", None),
    ("Pass 2 · A — Magnetic resonance physics", "pass2_deep_dive", "A"),
    ("Pass 2 · B — The MRI system (hardware)", "pass2_deep_dive", "B"),
    ("Pass 2 · C — The MRI experiment", "pass2_deep_dive", "C"),
    ("Pass 2 · D — Contrast", "pass2_deep_dive", "D"),
    ("Pass 2 · E — Radiofrequency pulses", "pass2_deep_dive", "E"),
    ("Pass 2 · F — Image formation", "pass2_deep_dive", "F"),
    ("Pass 2 · G — Image characteristics", "pass2_deep_dive", "G"),
    ("Pass 2 · H — Fast imaging", "pass2_deep_dive", "H"),
    ("Pass 2 · I — Imperfections & artifacts", "pass2_deep_dive", "I"),
    ("Pass 2 · J — Advanced & fun topics", "pass2_deep_dive", "J"),
    ("Refreshers — math", "refreshers", "RM"),
    ("Refreshers — physics", "refreshers", "RP"),
    ("Reference", "reference", None),
]
REFERENCE_ORDER = ["Notation_and_Symbols", "Glossary_and_Acronyms", "Key_MRI_Concepts",
                   "MRI_Math_Concepts", "Questions", "Software_Resources"]

CONFIG = """\
# Generated by _authoring/make_book.py — edit there, not here.
title: "MRI: from intuition to engineering"
author: "Adapted from P. E. Z. Larson, Principles of MRI (MIT License)"
logo: images/MRI_logo-retro.png
copyright: "2026"
only_build_toc_files: true
exclude_patterns: [_build, _site, _authoring, "**.ipynb_checkpoints", README.md]

execute:
  execute_notebooks: "off"      # notebooks are stored already executed

parse:
  myst_enable_extensions:
    - dollarmath
    - amsmath
    - html_image
    - html_admonition

sphinx:
  config:
    html_show_copyright: false
    suppress_warnings: ["myst.header", "myst.xref_missing", "mystnb.unknown_mime_type"]
    nb_merge_streams: true

repository:
  url: https://github.com/DominikVincent/MRI-education-resources
  branch: mri-course

html:
  home_page_in_navbar: true
  use_repository_button: true
  use_issues_button: false
  extra_footer: |
    <p>Adapted and extended from P. E. Z. Larson, <a href="https://larsonlab.github.io/MRI-education-resources">Principles of MRI</a>
    (<a href="https://doi.org/10.5281/zenodo.5547020">doi:10.5281/zenodo.5547020</a>), MIT License.</p>
"""


def chapters(folder, prefix):
    names = sorted(f[:-6] for f in os.listdir(os.path.join(ROOT, folder)) if f.endswith(".ipynb"))
    if folder == "reference":
        names = [n for n in REFERENCE_ORDER if n in names] + [n for n in names if n not in REFERENCE_ORDER]
    if prefix:
        names = [n for n in names if n.startswith(prefix) and (len(prefix) > 1 or n[1].isdigit())]
    return [f"{folder}/{n}" for n in names]


def main():
    lines = ["# Generated by _authoring/make_book.py — edit there, not here.",
             "format: jb-book", "root: 00_Start_Here", "parts:"]
    for caption, folder, prefix in PARTS:
        files = chapters(folder, prefix)
        if not files:
            continue
        lines.append(f'  - caption: "{caption}"')
        lines.append("    chapters:")
        lines += [f'      - file: "{f}"' for f in files]
    with open(os.path.join(ROOT, "_toc.yml"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(ROOT, "_config.yml"), "w") as f:
        f.write(CONFIG)
    print("wrote _toc.yml and _config.yml")
    if "--no-build" not in sys.argv:
        jb = os.path.join(os.path.dirname(sys.executable), "jb")
        subprocess.run([jb, "build", ROOT, "--quiet"], check=False)


if __name__ == "__main__":
    main()
